const helloBrCountries = ['br', 'br-pt'];

// Returns the component for a page JSON key, applying the Hello Brazil overrides.
export function resolveSection(key, pageInfo) {
    if (pageInfo?.page === 'hello' && helloBrCountries.includes(pageInfo?.country)) {
        if (key === 'Banner') return HelloBanner;
        if (key === 'Features') return HelloBrFeatures;
    }
    return Components[key];
}
